import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import type { FeedbackWorkspaceView } from '../feedback'
import { createAttachmentController } from './attachmentController'
import { controllerContext, fileCandidate, mocks, resetAttachmentMocks } from './attachmentControllerTestHarness'

const generated = { fileName: 'visual-feedback.png', contents: new Uint8Array([1, 2, 3]).buffer }
function workspace(id = 'request-1'): FeedbackWorkspaceView {
  return { request: { request_id: id, status: 'in_progress' }, attachments: [], draft: { saved_revision: 3 } } as unknown as FeedbackWorkspaceView
}
function harness() {
  const { context } = controllerContext()
  let current = workspace()
  context.getWorkspace = () => current
  context.applyWorkspaceMutation = vi.fn((next) => { current = next })
  mocks.applicationCall.mockImplementation(async (name, input) => {
    if (name === 'getFeedbackWorkspace') return current
    if (name === 'addFeedbackAttachment') {
      const revision = current.draft.saved_revision + 1
      return { ...current, draft: { ...current.draft, saved_revision: revision }, attachments: [...current.attachments,
        { attachment_id: `attachment-${revision}`, file_name: input.file_name, media_type: 'image/png' }] }
    }
  })
  return { context, controller: createAttachmentController(context), current: () => current, switchRequest: () => { current = workspace('request-2') } }
}

describe('generated workbench attachments', () => {
  beforeEach(resetAttachmentMocks)
  afterEach(() => vi.unstubAllGlobals())

  it('shares the user attachment queue and reconciles revisions without adding generated text', async () => {
    const { controller, context, current } = harness()
    const first = controller.persistAttachmentCandidates({ requestId: 'request-1', action: null }, [
      fileCandidate({ fileName: 'reference.png', byteLength: 1, readBytes: async () => new ArrayBuffer(1) }),
    ])
    const second = controller.persistGeneratedAttachment('request-1', generated)
    expect(await first).toBe(true)
    expect((await second).attachment_id).toBe('attachment-5')
    expect(mocks.applicationCall.mock.calls.filter(([name]) => name === 'addFeedbackAttachment').map(([, input]) => input.expected_revision)).toEqual([3, 4])
    expect(context.routeDraftOperation).toHaveBeenCalledOnce()
    expect(context.routeDraftOperation).toHaveBeenCalledWith('request-1', expect.objectContaining({ attachment: expect.objectContaining({ file_name: 'reference.png' }) }))
    expect(current().draft.saved_revision).toBe(5)
    expect(context.saveDraftNow).toHaveBeenCalledTimes(2)
  })

  it('does not upload when a draft save fails', async () => {
    const { controller, context } = harness()
    vi.mocked(context.saveDraftNow).mockResolvedValue(false)
    await expect(controller.persistGeneratedAttachment('request-1', generated)).rejects.toThrow('Save the draft')
    expect(mocks.applicationCall).not.toHaveBeenCalled()
  })

  it('does not apply an upload response to a different request', async () => {
    const { controller, context, switchRequest } = harness()
    const original = workspace()
    mocks.applicationCall.mockImplementation(async (name) => {
      if (name === 'getFeedbackWorkspace') return original
      if (name === 'addFeedbackAttachment') {
        switchRequest()
        return { ...original, draft: { ...original.draft, saved_revision: 4 }, attachments: [{ attachment_id: 'late', file_name: generated.fileName }] }
      }
    })
    await expect(controller.persistGeneratedAttachment('request-1', generated)).rejects.toThrow('request changed')
    expect(context.applyWorkspaceMutation).not.toHaveBeenCalled()
  })

  it('reconciles a lost upload response and reports failure without replaying or inserting it', async () => {
    const { controller, context, current } = harness()
    const stored = { ...current(), draft: { ...current().draft, saved_revision: 4 }, attachments: [{ attachment_id: 'saved', file_name: generated.fileName, media_type: 'image/png' }] }
    let uploaded = false
    mocks.applicationCall.mockImplementation(async (name) => {
      if (name === 'getFeedbackWorkspace') return uploaded ? stored : current()
      if (name === 'addFeedbackAttachment') { uploaded = true; throw new Error('Upload response lost') }
    })
    await expect(controller.persistGeneratedAttachment('request-1', generated)).rejects.toThrow('Upload response lost')
    expect(mocks.applicationCall.mock.calls.filter(([name]) => name === 'addFeedbackAttachment')).toHaveLength(1)
    expect(context.applyWorkspaceMutation).toHaveBeenCalledWith(stored)
    expect(context.routeDraftOperation).not.toHaveBeenCalled()
    expect(await controller.prepareFeedback('request-1')).toEqual({ kind: 'ready' })
  })

  it('rejects empty or oversized generated bytes before touching the queue', async () => {
    const { controller } = harness()
    await expect(controller.persistGeneratedAttachment('request-1', { ...generated, contents: new ArrayBuffer(0) })).rejects.toThrow('20 MiB')
    await expect(controller.persistGeneratedAttachment('request-1', { ...generated, contents: new ArrayBuffer(20 * 1024 * 1024 + 1) })).rejects.toThrow('20 MiB')
    expect(mocks.applicationCall).not.toHaveBeenCalled()
  })
})
