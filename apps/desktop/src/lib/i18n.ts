export function t(
  locale: Locale,
  source: string,
  values: Record<string, string | number> = {},
): string {
  let output = locale === 'en' ? (english[source] ?? source) : source
  for (const [key, value] of Object.entries(values)) {
    output = output.replaceAll(`{${key}}`, String(value))
  }
  return output
}
