export function agentText(locale: Locale, source: string): string {
  if (locale === 'zh-CN') {
    const invalidLine = /^Invalid environment variable on line (\d+)\. Use KEY=VALUE\.$/u.exec(source)
    if (invalidLine) return `第 ${invalidLine[1]} 行环境变量格式无效，请使用 KEY=VALUE。`
    const duplicateLine = /^Duplicate environment variable on line (\d+)\.$/u.exec(source)
    if (duplicateLine) return `第 ${duplicateLine[1]} 行存在重复的环境变量。`
    return chinese[source] ?? t(locale, source)
  }
  return t(locale, source)
}
